/**
 * Build-time secret encoder. Reads every password pool from the `JSHACK_SECRETS`
 * environment variable (validated by `parseSecrets`) and emits two gitignored modules:
 *
 * - `src/core/secrets/__encoded.ts`, the one the game imports: each list
 *   JSON-stringified and XOR+Base64 obfuscated (see `contentCodec.ts`), except that the
 *   uncrackable pool is replaced by `UNCRACKABLE_HASHES`, the md5 of each word in list
 *   order. Those words are the answer key to every door that holds, so the bundle
 *   carries only what a player would have to crack anyway. The other lists reach every
 *   player in the clear (the wordlist, a cracked wifi key), so obfuscation is enough.
 * - `src/core/secrets/__plaintext.ts`, the four raw lists, for tests and scripts that
 *   need the word behind a hash. Lint forbids it to production code.
 *
 * Run automatically by the `predev`/`prebuild`/`pretest*` npm hooks so both files are
 * always fresh.
 *
 * On Vercel the variable comes from the project's environment. Locally it is read
 * from `.env.development.local` when the shell does not set it. A missing or invalid
 * value stops the build with every broken rule named: there is no fallback list,
 * because a quiet fallback is exactly the wrong world this gate exists to prevent.
 */
import { existsSync, writeFileSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { md5 } from '../src/core/generation/md5.js';
import { encodeContent } from '../src/core/secrets/contentCodec.js';
import { parseSecrets } from '../src/core/secrets/parseSecrets.js';

const scriptDir = dirname(fileURLToPath(import.meta.url));

const localEnvFile = resolve(scriptDir, '../.env.development.local');
if (process.env['JSHACK_SECRETS'] === undefined && existsSync(localEnvFile)) {
  process.loadEnvFile(localEnvFile);
}

const parsed = parseSecrets(process.env['JSHACK_SECRETS']);
if (!parsed.ok) {
  console.error(parsed.error);
  process.exit(1);
}

const { UNCRACKABLE_PASSWORDS, ...readableLists } = parsed.secrets;
const bundledLists = { ...readableLists, UNCRACKABLE_HASHES: UNCRACKABLE_PASSWORDS.map(md5) };

const encodedEntries = Object.entries(bundledLists).map(
  ([key, words]) => [key, encodeContent(JSON.stringify(words))] as const,
);

const encodedLines = [
  '// Auto-generated by scripts/encode.ts — do not edit.',
  "import { decodeContent } from './contentCodec.js';",
  '',
  'const d = (encoded: string): string => decodeContent(encoded);',
  '',
  'export const secrets = {',
  ...encodedEntries.map(([key, encoded]) => `  ${key}: d(${JSON.stringify(encoded)}),`),
  '} as const;',
  '',
];

const plaintextLines = [
  '// Auto-generated by scripts/encode.ts — do not edit. Tests and scripts only.',
  '',
  ...Object.entries(parsed.secrets).map(
    ([key, words]) => `export const ${key}: readonly string[] = ${JSON.stringify(words)};`,
  ),
  '',
];

const write = (fileName: string, lines: readonly string[]): void => {
  const outPath = resolve(scriptDir, '../src/core/secrets', fileName);
  writeFileSync(outPath, lines.join('\n'), 'utf-8');
  console.log(`Wrote ${outPath}`);
};

write('__encoded.ts', encodedLines);
write('__plaintext.ts', plaintextLines);
